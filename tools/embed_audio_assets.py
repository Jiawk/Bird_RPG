SIGNATURES = {".mp3": (b"ID3", b"\xff\xfb", b"\xff\xf3", b"\xff\xf2"), ".wav": (b"RIFF",)}

def verify_source(path: Path) -> None:
    if not path.is_file():
        raise SystemExit(f"missing source: {path}")
    signatures = SIGNATURES.get(path.suffix.lower())
    if not signatures or not path.read_bytes().startswith(signatures):
        raise SystemExit(f"unexpected source format: {path}")

def verify_m4a(path: Path) -> None:
    if not path.is_file() or b"ftyp" not in path.read_bytes()[:32]:
        raise SystemExit(f"missing or invalid AAC/M4A asset: {path}")

def main() -> None:
    keys = [key for key, _, _ in MANIFEST]
    if len(keys) != len(set(keys)):
        raise SystemExit("manifest contains duplicate canonical keys")
    out = ["/* Generated by tools/embed_audio_assets.py. Do not edit manually. */", "const AUDIO_ASSET_REGISTRY = Object.freeze({"]
    for key, source_rel, encoded_rel in MANIFEST:
        source, encoded = ROOT / source_rel, ROOT / encoded_rel
        verify_source(source)
        verify_m4a(encoded)
        data = base64.b64encode(encoded.read_bytes()).decode("ascii")
        out.append(f"  {key}: Object.freeze({{ sourcePath: {source_rel!r}, mime: 'audio/mp4', data: 'data:audio/mp4;base64,{data}' }}),")
    out.extend(["});", "const AUDIO_ASSET_KEYS = Object.freeze(Object.keys(AUDIO_ASSET_REGISTRY));", ""])
    (ROOT / "js/audio-assets.js").write_text("\n".join(out), encoding="utf-8")
    print(f"generated js/audio-assets.js with {len(keys)} canonical assets")

if __name__ == "__main__":
    main()
